#!/usr/bin/env python3
"""Build assets/product-pdp-wide.css: the product landing page scaled for screens wider than 1440px.

The landing page is laid out at 1440px. On wider screens every pixel size in the desktop rules (font sizes, padding,
margins, gaps, fixed widths/heights, radii, offsets, grid tracks) becomes clamp(Npx, N/14.4 vw, N*4/3 px), so the
page grows in proportion up to 1.33x at 1920px and stops there. Real CSS values only (no zoom, no transform).

Sources: assets/product-pdp.css and ../site-footer/assets/site-footer.css (footer rules are prefixed with
body.single-product so only product pages are affected). Rules for phones/tablets (max-width queries) are left out.
Run:  python3 tools/gen-wide.py
"""
import re, pathlib, tinycss2

HERE = pathlib.Path(__file__).resolve().parent.parent
BASE = 1440.0
MAXK = 4 / 3
PROPS = {'font-size', 'line-height', 'height', 'min-height', 'max-height', 'width', 'min-width', 'max-width',
         'padding', 'padding-top', 'padding-right', 'padding-bottom', 'padding-left',
         'margin', 'margin-top', 'margin-right', 'margin-bottom', 'margin-left',
         'gap', 'row-gap', 'column-gap', 'border-radius', 'top', 'right', 'bottom', 'left', 'inset',
         'flex-basis', 'grid-template-columns', 'grid-template-rows', 'grid-auto-rows', 'scroll-margin-top'}
PX = re.compile(r'(?<![\w.#-])(-?\d*\.?\d+)px')

def fluid(m):
    n = float(m.group(1))
    if abs(n) < 3:
        return m.group(0)
    a = abs(n); s = lambda x: ('%.2f' % x).rstrip('0').rstrip('.')
    c = 'clamp(%spx, %svw, %spx)' % (s(a), s(a / BASE * 100), s(a * MAXK))
    return c if n > 0 else 'calc(-1 * %s)' % c

def media_applies(prelude):
    p = prelude.replace(' ', '')
    if 'max-width' in p or 'print' in p or 'prefers-reduced-motion' in p or 'hover' in p:
        return False
    return 'min-width' in p

def convert(css, prefix='', skip=()):
    out = []
    def rule(r):
        sel = tinycss2.serialize(r.prelude).strip()
        if any(k in sel for k in skip):
            return
        decls = []
        for d in tinycss2.parse_declaration_list(r.content, skip_comments=True, skip_whitespace=True):
            if d.type != 'declaration' or d.name.startswith('--') or d.lower_name not in PROPS:
                continue
            v = tinycss2.serialize(d.value).strip()
            if re.search(r'vw|vh|clamp\(', v):
                continue
            if d.lower_name == 'max-width' and any(float(x) > 900 for x in re.findall(r'(\d*\.?\d+)px', v)):
                continue
            nv = PX.sub(fluid, v)
            if nv != v:
                decls.append('%s:%s%s' % (d.name, nv, ' !important' if d.important else ''))
        if decls:
            if prefix:
                sel = ', '.join(prefix + ' ' + s.strip() for s in sel.split(','))
            out.append('%s{ %s; }' % (sel, '; '.join(decls)))
    for r in tinycss2.parse_stylesheet(css, skip_comments=True, skip_whitespace=True):
        if r.type == 'qualified-rule':
            rule(r)
        elif r.type == 'at-rule' and r.lower_at_keyword == 'media' and media_applies(tinycss2.serialize(r.prelude)):
            for rr in tinycss2.parse_rule_list(r.content, skip_comments=True, skip_whitespace=True):
                if rr.type == 'qualified-rule':
                    rule(rr)
    return out

pdp = convert((HERE / 'assets/product-pdp.css').read_text(), skip=('ast-container',))
foot = convert((HERE.parent / 'site-footer/assets/site-footer.css').read_text(), prefix='body.single-product')
head = ('/* GENERATED by tools/gen-wide.py from product-pdp.css and site-footer.css: do not edit by hand.\n'
        '   Product landing page on screens wider than 1440px: pixel sizes grow with the viewport (up to 1.33x at 1920px). */\n'
        '@media (min-width:1441px){\n')
tail = ('\n/* the landing column: 1340px at 1440, growing with the screen (about 1786px at 1920) */\n'
        'body.single-product .site-content > .ast-container{ max-width:min(100%, 1920px) !important; padding-left:min(3.47vw, 66.67px) !important; padding-right:min(3.47vw, 66.67px) !important; }\n'
        'body.single-product #masthead .site-primary-header-wrap.ast-container{ max-width:min(100%, 1920px) !important; padding-left:min(3.47vw, 66.67px) !important; padding-right:min(3.47vw, 66.67px) !important; }\n'
        '}\n')
(HERE / 'assets/product-pdp-wide.css').write_text(head + '\n'.join(pdp + foot) + tail)
print('rules:', len(pdp), '+', len(foot))
