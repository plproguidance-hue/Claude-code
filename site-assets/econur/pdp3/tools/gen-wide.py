#!/usr/bin/env python3
"""Build assets/product-pdp-wide.css: the product landing page sized for screens wider than 1440px.

On screens wider than 1440px every pixel size in the desktop rules (font sizes, padding, margins, gaps, fixed
widths/heights, radii, offsets, grid tracks) is multiplied by SCALE (0.85 = 15% smaller, as approved by the owner).
The landing column keeps its 1340px width, so photos and grids keep their size and the page does not get narrower.
Real CSS values only (no zoom, no transform). Change SCALE and re-run to make it bigger or smaller.

Sources: assets/product-pdp.css and ../site-footer/assets/site-footer.css (footer rules are prefixed with
body.single-product so only product pages are affected). Rules for phones/tablets (max-width queries) are left out.
Run:  python3 tools/gen-wide.py
"""
import re, pathlib, tinycss2

HERE = pathlib.Path(__file__).resolve().parent.parent
BASE = 1440.0
import os
SCALE = float(os.environ.get("ECN_SCALE", 0.85))
PROPS = {'font-size', 'line-height', 'height', 'min-height', 'max-height', 'width', 'min-width', 'max-width',
         'padding', 'padding-top', 'padding-right', 'padding-bottom', 'padding-left',
         'margin', 'margin-top', 'margin-right', 'margin-bottom', 'margin-left',
         'gap', 'row-gap', 'column-gap', 'border-radius', 'top', 'right', 'bottom', 'left', 'inset',
         'flex-basis', 'grid-template-columns', 'grid-template-rows', 'grid-auto-rows', 'scroll-margin-top'}
PX = re.compile(r'(?<![\w.#-])(-?\d*\.?\d+)px')

def fluid(m):
    n = float(m.group(1))
    if abs(n) < 3:
        return m.group(0)
    return ('%.2f' % (n * SCALE)).rstrip('0').rstrip('.') + 'px'

def media_applies(prelude):
    p = prelude.replace(' ', '')
    if 'max-width' in p or 'print' in p or 'prefers-reduced-motion' in p or 'hover' in p:
        return False
    return 'min-width' in p

def convert(css, prefix='', skip=()):
    out = []
    def rule(r):
        sel = tinycss2.serialize(r.prelude).strip()
        if any(k in sel for k in skip):
            return
        decls = []
        for d in tinycss2.parse_declaration_list(r.content, skip_comments=True, skip_whitespace=True):
            if d.type != 'declaration' or d.name.startswith('--') or d.lower_name not in PROPS:
                continue
            # every sizing declaration is repeated in source order (scaled where it has pixel values), so the
            # cascade inside the wide sheet is exactly the cascade of the source sheets
            v = tinycss2.serialize(d.value).strip()
            keep = re.search(r'vw|vh|clamp\(', v) or (d.lower_name == 'max-width' and any(float(x) > 900 for x in re.findall(r'(\d*\.?\d+)px', v)))
            nv = v if keep else PX.sub(fluid, v)
            decls.append('%s:%s%s' % (d.name, nv, ' !important' if d.important else ''))
        if decls:
            if prefix:
                sel = ', '.join(prefix + ' ' + s.strip() for s in sel.split(','))
            out.append('%s{ %s; }' % (sel, '; '.join(decls)))
    for r in tinycss2.parse_stylesheet(css, skip_comments=True, skip_whitespace=True):
        if r.type == 'qualified-rule':
            rule(r)
        elif r.type == 'at-rule' and r.lower_at_keyword == 'media' and media_applies(tinycss2.serialize(r.prelude)):
            for rr in tinycss2.parse_rule_list(r.content, skip_comments=True, skip_whitespace=True):
                if rr.type == 'qualified-rule':
                    rule(rr)
    return out

# the top product section (gallery + purchase panel) keeps one size on every desktop screen: left out on purpose
HERO = ('ast-container', 'ecn-lp-hero', '.ecn-g', 'ecn-lp-badges', 'ecn-lp-card', 'ecn-pdp-info', 'ecn-pdp-cat', 'ecn-pdp-rating',
        'ecn-pdp-titlerow', 'ecn-pdp-title', 'ecn-pdp-stock', 'ecn-lp-sub', 'ecn-lp-pricerow', 'ecn-pdp-price', 'ecn-pdp-size',
        'ecn-lp-checks', 'ecn-lp-pack', 'ecn-lp-label', 'ecn-pdp-sizes', 'ecn-pdp-sz', 'ecn-lp-ptype', 'form.cart', 'ecn-qty',
        'single_add_to_cart_button', 'ecn-pdp-buynow', 'ecn-pdp-wa', 'ecn-lp-service', 'ecn-pdp-coming', 'variations',
        'woocommerce-variation', 'ecn-pdp-firstrev', 'ecn-atc-price', '#primary', 'reset_variations', 'ecn-flag')
pdp = convert((HERE / 'assets/product-pdp.css').read_text(), skip=HERO)
foot = convert((HERE.parent / 'site-footer/assets/site-footer.css').read_text(), prefix='body.single-product')
head = ('/* GENERATED by tools/gen-wide.py from product-pdp.css and site-footer.css: do not edit by hand.\n'
        '   Product landing page on screens wider than 1440px: pixel sizes x %s (column width unchanged). */\n'
        '@media (min-width:1441px){\n') % SCALE
tail = '\n}\n'
(HERE / 'assets/product-pdp-wide.css').write_text(head + '\n'.join(pdp + foot) + tail)
print('rules:', len(pdp), '+', len(foot))
